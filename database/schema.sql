create extension if not exists pgcrypto;


-- =========================================================
-- ANIME
-- =========================================================

create table if not exists public.anime (
  id bigint generated by default as identity primary key,

  -- Nom utilisé par TON application
  name text not null,

  -- Image principale de l'anime
  image_url text,

  -- Petite version de l'image
  image_small_url text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint anime_name_unique unique (name)
);


-- =========================================================
-- IDS MAL / TENRAI
-- =========================================================
--
-- Un anime de notre application peut correspondre
-- à plusieurs entrées MyAnimeList.
--
-- Exemple :
--
-- Shingeki no Kyojin
--   ├── 16498
--   ├── 25777
--   ├── 35760
--   └── 40028
--

create table if not exists public.anime_sources (
  id bigint generated by default as identity primary key,

  anime_id bigint not null
    references public.anime(id)
    on delete cascade,

  mal_id integer not null,

  created_at timestamptz not null default now(),

  constraint anime_sources_mal_id_unique
    unique (mal_id),

  constraint anime_sources_anime_mal_unique
    unique (anime_id, mal_id)
);


create index if not exists idx_anime_sources_anime_id
on public.anime_sources(anime_id);


-- =========================================================
-- PERSONNAGES
-- =========================================================

create table if not exists public.characters (
  id bigint generated by default as identity primary key,

  -- ID MAL du personnage
  mal_id integer not null unique,

  name text not null,

  image_url text,

  image_small_url text,

  -- Informations récupérées depuis Tenrai
  role text,

  mal_favorites integer not null default 0,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


create index if not exists idx_characters_name
on public.characters using gin (
  to_tsvector('simple', name)
);

create index if not exists idx_characters_favorites
on public.characters(mal_favorites desc);


-- =========================================================
-- RELATION ANIME <-> PERSONNAGES
-- =========================================================

create table if not exists public.anime_characters (
  anime_id bigint not null
    references public.anime(id)
    on delete cascade,

  character_id bigint not null
    references public.characters(id)
    on delete cascade,

  created_at timestamptz not null default now(),

  primary key (anime_id, character_id)
);


create index if not exists idx_anime_characters_character_id
on public.anime_characters(character_id);


-- =========================================================
-- UPDATED_AT
-- =========================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


drop trigger if exists anime_set_updated_at
on public.anime;

create trigger anime_set_updated_at
before update on public.anime
for each row
execute function public.set_updated_at();


drop trigger if exists characters_set_updated_at
on public.characters;

create trigger characters_set_updated_at
before update on public.characters
for each row
execute function public.set_updated_at();


