-- =========================================================
-- VUE COMPLETE POUR LES JEUX
-- =========================================================

create or replace view public.character_catalog as
select
  c.id,
  c.mal_id,
  c.name,
  c.image_url,
  c.image_small_url,
  c.role,
  c.mal_favorites,

  a.id as anime_id,
  a.name as anime_name,
  a.image_url as anime_image_url,
  a.image_small_url as anime_image_small_url

from public.characters c

join public.anime_characters ac
  on ac.character_id = c.id

join public.anime a
  on a.id = ac.anime_id;

-- =========================================================
-- RANDOM ANIME
-- =========================================================

create or replace function public.get_random_anime()
returns setof public.anime
language sql
security definer
set search_path = public
as $$
  select *
  from public.anime
  order by random()
  limit 1;
$$;


-- =========================================================
-- RANDOM CHARACTER
-- =========================================================

create or replace function public.get_random_character()
returns setof public.characters
language sql
security definer
set search_path = public
as $$
  select *
  from public.characters
  order by random()
  limit 1;
$$;


-- =========================================================
-- RANDOM CHARACTERS
-- =========================================================

create or replace function public.get_random_characters(
  requested_count integer
)
returns setof public.characters
language sql
security definer
set search_path = public
as $$
  select *
  from public.characters
  order by random()
  limit greatest(requested_count, 0);
$$;